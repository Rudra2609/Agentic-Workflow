"""Final-report compiler (Sprint 9 item 9.20): ``make report`` gathers every member's
``docs/members/<n>/{research,design,eval}.md`` into one report skeleton, in member order.

    uv run python -m hmap.agents.docgen.compile_report                 # -> reports/final-report.md
    uv run python -m hmap.agents.docgen.compile_report --out x.md

Headings move down two levels (each member is a chapter, each document a section), relative links are rewritten
to work from the report's folder, and a table at the top says which documents are still missing. The output is
regenerated, never edited by hand (``reports/`` is git-ignored).
"""

import argparse
import os
import re
from datetime import UTC, datetime
from pathlib import Path

from hmap.core.config import REPO_ROOT

PARTS = (("research", "Research"), ("design", "Design"), ("eval", "Evaluation"))
LINK = re.compile(r"(\]\()([^)#\s]+)([^)]*\))")


def member_dirs(docs: Path) -> list[Path]:
    return sorted((p for p in docs.glob("members/*") if p.is_dir() and p.name.isdigit()), key=lambda p: int(p.name))


def title_of(folder: Path) -> str:
    """The member's subsystem, from the first heading of their README or plan (else "Member <n>")."""
    for name in ("README.md", "plan.md", "research.md"):
        f = folder / name
        if f.is_file():
            m = re.search(r"^#\s+(.+)$", f.read_text(encoding="utf-8"), re.M)
            if m:
                return re.sub(r"^Member\s+\d+\s*[—:-]\s*", "", m.group(1).strip())
    return f"Member {folder.name}"


def shift(md: str, levels: int, source: Path, out_dir: Path) -> str:
    out = []
    fence = False
    for line in md.splitlines():
        if line.lstrip().startswith("```"):
            fence = not fence
        if not fence and (m := re.match(r"^(#{1,6})(\s.*)$", line)):
            line = "#" * min(6, len(m.group(1)) + levels) + m.group(2)
        out.append(line)
    text = "\n".join(out)

    def relink(m: re.Match[str]) -> str:
        target = m.group(2)
        if re.match(r"^[a-z]+:", target) or target.startswith("/"):
            return m.group(0)
        resolved = (source.parent / target).resolve()
        return m.group(1) + os.path.relpath(resolved, out_dir.resolve()) + m.group(3)

    return LINK.sub(relink, text)


def compile_report(root: Path = REPO_ROOT, out: Path | None = None) -> tuple[Path, list[str]]:
    docs = root / "docs"
    out = out or root / "reports" / "final-report.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    members = member_dirs(docs)
    missing: list[str] = []
    rows = []
    chapters = []
    for folder in members:
        have = []
        body = [f"## Member {folder.name}: {title_of(folder)}", ""]
        for name, label in PARTS:
            f = folder / f"{name}.md"
            if not f.is_file() or len(f.read_text(encoding="utf-8").strip()) < 200:
                missing.append(f"docs/members/{folder.name}/{name}.md")
                have.append("—")
                continue
            have.append("yes")
            body += [f"### {label}", "", shift(f.read_text(encoding="utf-8"), 3, f, out.parent).strip(), ""]
        rows.append(f"| {folder.name} | {title_of(folder)} | " + " | ".join(have) + " |")
        chapters.append("\n".join(body))
    head = ["# Final report: hierarchical multi-agent platform (skeleton)", "",
            f"Compiled by `make report` on {datetime.now(UTC):%Y-%m-%d} from "
            "`docs/members/*/{research,design,eval}.md`."
            " Regenerate it after editing a member document; do not edit this file.", "",
            "## Contents", "", "| Member | Subsystem | Research | Design | Evaluation |", "|---|---|---|---|---|",
            *rows, ""]
    if missing:
        head += ["Missing (or still a template): " + ", ".join(f"`{m}`" for m in missing) + ".", ""]
    out.write_text("\n".join(head) + "\n" + "\n\n".join(chapters).rstrip() + "\n", encoding="utf-8")
    return out, missing


def main() -> None:
    ap = argparse.ArgumentParser(description="Compile the final-report skeleton from the member documents.")
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()
    out, missing = compile_report(out=args.out)
    print(f"wrote {out} ({len(missing)} document(s) missing)")


if __name__ == "__main__":
    main()
